<#
.SYNOPSIS
    Auto-generates shared/skills/INDEX.md from the SKILL.md files.

.DESCRIPTION
    Reads the description from the YAML frontmatter of each SKILL.md and
    produces a markdown table in shared/skills/INDEX.md.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File bin\generate-skill-index.ps1
#>

$ErrorActionPreference = 'Stop'
$BinDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$SharedRoot = Split-Path -Parent $BinDir
$SkillsDir = Join-Path $SharedRoot 'shared\skills'
$IndexFile = Join-Path $SkillsDir 'INDEX.md'

function Get-FrontmatterValue {
    param(
        [Parameter(Mandatory=$true)][string]$Frontmatter,
        [Parameter(Mandatory=$true)][string]$Key
    )

    $lines = $Frontmatter -split "`r?`n"
    for ($i = 0; $i -lt $lines.Count; $i++) {
        $line = $lines[$i]
        if ($line -notmatch "^$([regex]::Escape($Key)):\s*(.*)$") {
            continue
        }

        $value = $Matches[1].Trim()
        if ($value -in @('>-', '>', '|-', '|')) {
            $parts = @()
            for ($j = $i + 1; $j -lt $lines.Count; $j++) {
                if ($lines[$j] -match '^[A-Za-z_-]+:') { break }
                $parts += $lines[$j].Trim()
            }
            return (($parts -join ' ') -replace '\s+', ' ').Trim()
        }

        return $value.Trim("'").Trim('"')
    }

    return ''
}

function Escape-MarkdownTableCell {
    param([string]$Value)

    return (($Value -replace '\|', '\|') -replace "`r?`n", ' ').Trim()
}

$skills = @()

foreach ($dir in Get-ChildItem -Path $SkillsDir -Directory | Sort-Object Name) {
    $skillFile = Join-Path $dir.FullName 'SKILL.md'
    if (-not (Test-Path $skillFile)) { continue }

    $content = Get-Content $skillFile -Raw -Encoding UTF8
    $name = $dir.Name

    # Extract description from YAML frontmatter. Keep this parser small and
    # predictable so it works on machines without a YAML module installed.
    $desc = ''
    if ($content -match '(?ms)^---\s*\n(.*?)\n---') {
        $frontmatter = $Matches[1]
        $frontmatterName = Get-FrontmatterValue -Frontmatter $frontmatter -Key 'name'
        $desc = Get-FrontmatterValue -Frontmatter $frontmatter -Key 'description'
        if ($frontmatterName) { $name = $frontmatterName }
    }

    # Fallback: use first heading after frontmatter
    if (-not $desc) {
        if ($content -match '(?m)^#\s+(.+)') {
            $desc = $Matches[1].Trim()
        }
    }

    $skills += [PSCustomObject]@{
        Name        = Escape-MarkdownTableCell $name
        Description = Escape-MarkdownTableCell $desc
    }
}

# Build markdown
$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("# Skill Index")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("<!-- Auto-generated by bin/generate-skill-index.ps1 - do not edit manually -->")
[void]$sb.AppendLine("<!-- Last generated: $(Get-Date -Format 'yyyy-MM-dd HH:mm') -->")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("| Skill | Description |")
[void]$sb.AppendLine("|-------|-------------|")

foreach ($s in $skills) {
    [void]$sb.AppendLine("| ``$($s.Name)`` | $($s.Description) |")
}

[void]$sb.AppendLine("")
[void]$sb.AppendLine("**Total: $($skills.Count) skills**")

[System.IO.File]::WriteAllText($IndexFile, $sb.ToString(), [System.Text.Encoding]::UTF8)
Write-Host "Generated $IndexFile with $($skills.Count) skills" -ForegroundColor Green
