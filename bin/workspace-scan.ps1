<#
.SYNOPSIS
    Scans all workspace repos and generates an architecture map at
    shared/memory/architecture-map.md.

.DESCRIPTION
    Walks every git repo in the workspace and extracts:
      - Tech stack (from manifest files: pom.xml, package.json, etc.)
      - Service ports (from docker-compose, application.yml)
      - Inter-service references (grep for sibling repo names)
      - API endpoints (grep for @Path, @RequestMapping, router patterns)
      - Database references
      - Message queue references

    Output is a single markdown file that gives agents a bird's eye view
    of how services connect, what tech each uses, and where APIs live.

.PARAMETER Root
    Workspace root to scan. Defaults to parent of .copilot-shared.

.EXAMPLE
    powershell -File bin\workspace-scan.ps1
#>

$RootCompleter = {
    param($wordToComplete, $commandAst, $cursorPosition)
    try {
        $parent = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
        Get-ChildItem -Path $parent -Directory | Where-Object { Test-Path (Join-Path $_.FullName '.git') } | Select-Object -ExpandProperty Name | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
            [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', 'Repository')
        }
    } catch { }
}

param(
    [ArgumentCompleter($RootCompleter)]
    [string]$Root
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$BinDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$SharedRoot = Split-Path -Parent $BinDir
$MemoryDir = Join-Path $SharedRoot 'shared\memory'
$OutputFile = Join-Path $MemoryDir 'architecture-map.md'

if (-not $Root) {
    $Root = Split-Path -Parent $SharedRoot
}

Write-Host "`n=== workspace-scan ===" -ForegroundColor Cyan
Write-Host "  workspace: $Root"
Write-Host ""

$repos = Get-ChildItem -Path $Root -Directory |
    Where-Object { $_.Name -ne '.copilot-shared' -and (Test-Path (Join-Path $_.FullName '.git')) } |
    Sort-Object Name

$repoNames = $repos | ForEach-Object { $_.Name }

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("# Architecture Map")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("<!-- Auto-generated by bin/workspace-scan.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm') -->")
[void]$sb.AppendLine("<!-- Re-run: powershell -File .copilot-shared\bin\workspace-scan.ps1 -->")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("## Workspace Overview")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("- Repos scanned: $($repos.Count)")
[void]$sb.AppendLine("- Generated: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')")
[void]$sb.AppendLine("")

# --- Tech Stack Detection ---
[void]$sb.AppendLine("## Tech Stacks")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("| Repo | Language | Build | Framework | Has Docker |")
[void]$sb.AppendLine("|------|----------|-------|-----------|-----------|")

$repoData = @{}

foreach ($repo in $repos) {
    $name = $repo.Name
    $path = $repo.FullName
    $lang = 'Unknown'
    $build = '-'
    $framework = '-'
    $hasDocker = 'No'

    # Detect tech stack
    if (Test-Path (Join-Path $path 'pom.xml')) {
        $lang = 'Java'
        $build = 'Maven'
        $pomContent = Get-Content (Join-Path $path 'pom.xml') -Raw -ErrorAction SilentlyContinue
        if ($pomContent -match 'spring-boot') { $framework = 'Spring Boot' }
        elseif ($pomContent -match 'akka') { $framework = 'Akka' }
        elseif ($pomContent -match 'jersey|jax-rs') { $framework = 'JAX-RS' }
    }
    elseif (Test-Path (Join-Path $path 'build.gradle')) {
        $lang = 'Java/Kotlin'
        $build = 'Gradle'
    }
    elseif (Test-Path (Join-Path $path 'package.json')) {
        $lang = 'TypeScript/JS'
        $build = 'npm'
        $pkgContent = Get-Content (Join-Path $path 'package.json') -Raw -ErrorAction SilentlyContinue
        if ($pkgContent -match '"react"') { $framework = 'React' }
        elseif ($pkgContent -match '"angular"') { $framework = 'Angular' }
        elseif ($pkgContent -match '"vue"') { $framework = 'Vue' }
        elseif ($pkgContent -match '"express"') { $framework = 'Express' }
    }
    elseif (Test-Path (Join-Path $path 'go.mod')) {
        $lang = 'Go'
        $build = 'go'
    }
    elseif (Test-Path (Join-Path $path 'requirements.txt')) {
        $lang = 'Python'
        $build = 'pip'
    }
    elseif (Test-Path (Join-Path $path 'Cargo.toml')) {
        $lang = 'Rust'
        $build = 'cargo'
    }

    # Detect Docker
    $dockerFiles = @(
        'Dockerfile', 'docker-compose.yml', 'docker-compose.yaml',
        'Dockerfile.dev', 'Dockerfile.prod'
    )
    foreach ($df in $dockerFiles) {
        if (Test-Path (Join-Path $path $df)) { $hasDocker = 'Yes'; break }
    }

    [void]$sb.AppendLine("| ``$name`` | $lang | $build | $framework | $hasDocker |")

    $repoData[$name] = @{
        Language = $lang
        Build = $build
        Framework = $framework
        HasDocker = $hasDocker
        Path = $path
    }
}

[void]$sb.AppendLine("")

# --- Inter-Service References ---
[void]$sb.AppendLine("## Inter-Service References")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("Which repos reference other repos (by name in source code):")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("| Repo | References to other repos |")
[void]$sb.AppendLine("|------|--------------------------|")

foreach ($repo in $repos) {
    $name = $repo.Name
    $path = $repo.FullName
    $refs = @()

    # Look for references to sibling repo names in key config files
    $searchFiles = @()
    $candidates = @(
        'docker-compose.yml', 'docker-compose.yaml',
        'pom.xml', 'build.gradle', 'package.json',
        'application.yml', 'application.yaml', 'application.properties'
    )
    foreach ($c in $candidates) {
        $cp = Join-Path $path $c
        if (Test-Path $cp) { $searchFiles += $cp }
    }

    # Also check src/**/application.yml
    $appYmls = @(Get-ChildItem -Path $path -Recurse -Filter 'application.yml' -ErrorAction SilentlyContinue |
        Where-Object { $_.FullName -notmatch 'node_modules|\.git|target|build|dist' } |
        Select-Object -First 5)
    $searchFiles += ($appYmls | ForEach-Object { $_.FullName })

    foreach ($sf in $searchFiles) {
        if (-not (Test-Path $sf)) { continue }
        $content = Get-Content $sf -Raw -ErrorAction SilentlyContinue
        if (-not $content) { continue }

        foreach ($sibling in $repoNames) {
            if ($sibling -eq $name) { continue }
            # Normalize: kvision_foo → also check kvision-foo, kvision.foo
            $patterns = @($sibling, $sibling.Replace('_', '-'), $sibling.Replace('_', '.'))
            foreach ($pat in $patterns) {
                if ($content -match [regex]::Escape($pat)) {
                    if ($refs -notcontains $sibling) { $refs += $sibling }
                    break
                }
            }
        }
    }

    $refStr = if ($refs.Count -gt 0) { ($refs | ForEach-Object { "``$_``" }) -join ', ' } else { '-' }
    [void]$sb.AppendLine("| ``$name`` | $refStr |")
}

[void]$sb.AppendLine("")

# --- API / Port Detection ---
[void]$sb.AppendLine("## Service Ports")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("| Repo | Port(s) | Source |")
[void]$sb.AppendLine("|------|---------|--------|")

foreach ($repo in $repos) {
    $name = $repo.Name
    $path = $repo.FullName
    $ports = @()
    $source = '-'

    # Check docker-compose
    $dcFile = $null
    foreach ($f in @('docker-compose.yml', 'docker-compose.yaml')) {
        $fp = Join-Path $path $f
        if (Test-Path $fp) { $dcFile = $fp; break }
    }
    if ($dcFile) {
        $dcContent = Get-Content $dcFile -Raw -ErrorAction SilentlyContinue
        $portMatches = [regex]::Matches($dcContent, '(?m)"?(\d{4,5}):(\d{4,5})"?')
        foreach ($m in $portMatches) {
            $p = $m.Groups[1].Value
            if ($ports -notcontains $p) { $ports += $p }
        }
        if ($ports.Count -gt 0) { $source = 'docker-compose' }
    }

    # Check application.yml/properties for server.port
    if ($ports.Count -eq 0) {
        $appFiles = @(Get-ChildItem -Path $path -Recurse -Filter 'application.*' -ErrorAction SilentlyContinue |
            Where-Object { $_.Name -match 'application\.(yml|yaml|properties)$' -and $_.FullName -notmatch 'node_modules|\.git|target|build|dist' } |
            Select-Object -First 3)
        foreach ($af in $appFiles) {
            $afContent = Get-Content $af.FullName -Raw -ErrorAction SilentlyContinue
            if ($afContent -match 'server[.:]port[=: ]+(\d+)') {
                $p = $Matches[1]
                if ($ports -notcontains $p) { $ports += $p; $source = $af.Name }
            }
            if ($afContent -match 'port:\s*(\d{4,5})') {
                $p = $Matches[1]
                if ($ports -notcontains $p) { $ports += $p; $source = $af.Name }
            }
        }
    }

    $portStr = if ($ports.Count -gt 0) { $ports -join ', ' } else { '-' }
    [void]$sb.AppendLine("| ``$name`` | $portStr | $source |")
}

[void]$sb.AppendLine("")

# --- Message Queue Detection ---
[void]$sb.AppendLine("## Message Queues / Events")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("| Repo | Type | Evidence |")
[void]$sb.AppendLine("|------|------|----------|")

foreach ($repo in $repos) {
    $name = $repo.Name
    $path = $repo.FullName
    $mqType = @()
    $evidence = @()

    # Check pom.xml for amqp/rabbit/kafka
    $pomPath = Join-Path $path 'pom.xml'
    if (Test-Path $pomPath) {
        $pom = Get-Content $pomPath -Raw -ErrorAction SilentlyContinue
        if ($pom -match 'spring-boot-starter-amqp|rabbitmq|amqp-client') {
            $mqType += 'RabbitMQ'
            $evidence += 'pom.xml'
        }
        if ($pom -match 'kafka|spring-kafka') {
            $mqType += 'Kafka'
            $evidence += 'pom.xml'
        }
    }

    # Check package.json for amqplib/bull/kafka
    $pkgPath = Join-Path $path 'package.json'
    if (Test-Path $pkgPath) {
        $pkg = Get-Content $pkgPath -Raw -ErrorAction SilentlyContinue
        if ($pkg -match 'amqplib|amqp-connection-manager') {
            $mqType += 'RabbitMQ'
            $evidence += 'package.json'
        }
        if ($pkg -match 'kafkajs|node-kafka') {
            $mqType += 'Kafka'
            $evidence += 'package.json'
        }
    }

    if ($mqType.Count -gt 0) {
        [void]$sb.AppendLine("| ``$name`` | $($mqType -join ', ') | $($evidence -join ', ') |")
    }
}

[void]$sb.AppendLine("")

# --- Database Detection ---
[void]$sb.AppendLine("## Databases")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("| Repo | Type | Evidence |")
[void]$sb.AppendLine("|------|------|----------|")

foreach ($repo in $repos) {
    $name = $repo.Name
    $path = $repo.FullName
    $dbTypes = @()
    $evidence = @()

    $pomPath = Join-Path $path 'pom.xml'
    if (Test-Path $pomPath) {
        $pom = Get-Content $pomPath -Raw -ErrorAction SilentlyContinue
        if ($pom -match 'postgresql|postgres') { $dbTypes += 'PostgreSQL'; $evidence += 'pom.xml' }
        if ($pom -match 'mysql|mariadb') { $dbTypes += 'MariaDB/MySQL'; $evidence += 'pom.xml' }
        if ($pom -match 'elasticsearch|elastic') { $dbTypes += 'Elasticsearch'; $evidence += 'pom.xml' }
        if ($pom -match 'redis|jedis|lettuce') { $dbTypes += 'Redis'; $evidence += 'pom.xml' }
        if ($pom -match 'mongodb|mongo') { $dbTypes += 'MongoDB'; $evidence += 'pom.xml' }
    }

    $pkgPath = Join-Path $path 'package.json'
    if (Test-Path $pkgPath) {
        $pkg = Get-Content $pkgPath -Raw -ErrorAction SilentlyContinue
        if ($pkg -match 'pg|postgres') { $dbTypes += 'PostgreSQL'; $evidence += 'package.json' }
        if ($pkg -match 'redis|ioredis') { $dbTypes += 'Redis'; $evidence += 'package.json' }
        if ($pkg -match 'elasticsearch|@elastic') { $dbTypes += 'Elasticsearch'; $evidence += 'package.json' }
        if ($pkg -match 'mongoose|mongodb') { $dbTypes += 'MongoDB'; $evidence += 'package.json' }
    }

    if ($dbTypes.Count -gt 0) {
        $uniqueDb = $dbTypes | Select-Object -Unique
        $uniqueEv = $evidence | Select-Object -Unique
        [void]$sb.AppendLine("| ``$name`` | $($uniqueDb -join ', ') | $($uniqueEv -join ', ') |")
    }
}

[void]$sb.AppendLine("")
[void]$sb.AppendLine("---")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("## Summary")
[void]$sb.AppendLine("")

$langCounts = @{}
foreach ($rd in $repoData.Values) {
    $l = $rd.Language
    if (-not $langCounts.ContainsKey($l)) { $langCounts[$l] = 0 }
    $langCounts[$l]++
}
$dockerCount = ($repoData.Values | Where-Object { $_.HasDocker -eq 'Yes' }).Count

[void]$sb.AppendLine("- Total repos: $($repos.Count)")
foreach ($kv in ($langCounts.GetEnumerator() | Sort-Object Value -Descending)) {
    [void]$sb.AppendLine("- $($kv.Key): $($kv.Value) repos")
}
[void]$sb.AppendLine("- Dockerized: $dockerCount repos")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("---")
[void]$sb.AppendLine("<!-- To add detail: populate shared/memory/cross-repo-learnings.md with service communication specifics -->")

[System.IO.File]::WriteAllText($OutputFile, $sb.ToString(), [System.Text.Encoding]::UTF8)

Write-Host "workspace-scan completed" -ForegroundColor Green
Write-Host "  output: $OutputFile" -ForegroundColor Cyan
Write-Host "  repos scanned: $($repos.Count)" -ForegroundColor Cyan
